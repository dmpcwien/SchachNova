"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const css=fs.readFileSync("app/src/main/assets/schachnova-theme.css","utf8");
const js=fs.readFileSync("app/src/main/assets/live-coach.js","utf8");
const anchor=css.lastIndexOf("/* Coach feedback stays above the board");
assert(anchor>0,"Coach overlay rules must be present at the end of the stylesheet");
const layout=css.slice(anchor);
const panel=layout.match(/#gameScreen #liveCoachPanel:not\(\[hidden\]\)\s*\{([^}]*)\}/)?.[1];
const bubble=layout.match(/#gameScreen #liveCoachPanel \.coach-bubble\s*\{([^}]*)\}/)?.[1];
const message=layout.match(/#gameScreen #liveCoachMessage\s*\{([^}]*)\}/)?.[1];
assert(panel&&bubble&&message,"Coach panel, bubble and message need separate layout rules");
assert.match(panel,/height:116px!important/,"Changing coach message must not resize its normal layout footprint");
assert.match(panel,/z-index:20/,"Overlay should paint in front of chessboard");
assert.match(panel,/overflow:visible!important/,"Long text may extend beyond reserved panel height");
assert.match(bubble,/height:auto!important/);
assert.match(bubble,/max-height:none!important/);
assert.match(bubble,/overflow:visible!important/);
assert.match(message,/max-height:none!important/);
assert.match(message,/overflow:visible!important/);
assert.doesNotMatch(message,/overflow-y:auto|overflow-y:scroll/,"Coach explanation must not be internally scrollable");
assert.match(js,/function say\(t\)\{message\.textContent=t;\}/,"Text updates must not rebuild or reposition the board");
console.log("Coach feedback stays in a fixed layout slot and long explanations overlay the board instead of scrolling it");
