"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const {createPractice,keyOf,localDay,ownIndices}=require("../app/src/main/assets/practice-progress.js");
const root="app/src/main/assets/";
for(const file of ["practice-progress.js","training.js","chess.js"]){
 new vm.Script(fs.readFileSync(root+file,"utf8"),{filename:file});
}
const html=fs.readFileSync(root+"index.html","utf8");
for(const id of ["trainingDashboard","practiceToday","practiceStreak","practiceDue","practiceDailyBar","practiceGoalSelect","trainingNextDue"]){
 assert.ok(html.includes('id="'+id+'"'),"Missing learner UI: "+id);
}
assert.ok(html.indexOf('<script src="practice-progress.js"></script>')<html.indexOf('<script src="training.js"></script>'),"Learning store must initialize first");
const line={id:"it",title:"Italienisch",side:1,moves:["e2e4","e7e5","g1f3","b8c6","f1c4","g8f6"]};
const black={id:"sic",title:"Sizilianisch",side:-1,moves:["e2e4","c7c5","g1f3","d7d6"]};
assert.deepEqual(ownIndices(line),[0,2,4]);assert.deepEqual(ownIndices(black),[1,3]);
assert.notEqual(keyOf(line,0),keyOf(black,0));
let time=new Date(2026,10,3,12).getTime();
let raw=null;
const memory={getItem:k=>raw,setItem:(k,v)=>{raw=v;}};
const p=createPractice(memory,()=>time);
assert.equal(p.dayCount(),0);assert.equal(p.goal(),10);
assert.equal(p.recommendation([line,black]).line.id,"it","start with a default opening when practice is empty");
assert.equal(p.lineMetrics(line).mastery,"neu");
assert.equal(p.dueLines([line]).length,0);
p.noteMiss(line,0);
assert.equal(p.lineMetrics(line).missed,1);
assert.equal(p.lineMetrics(line).due,1);
assert.equal(p.recommendation([line,black]).line.id,"it","missed/due lines are recommended first");
p.noteMove(line,0,{hadMiss:true});
assert.equal(p.lineMetrics(line).seen,1,"wrong and corrected attempt is counted once");
assert.equal(p.lineMetrics(line).due,0,"corrected move is due tomorrow, not immediately");
assert.equal(p.dayCount(),1);
const first=p.noteMove(line,2);
assert.equal(first.firstTry,true);
assert.equal(first.level,1);
assert.equal(p.lineMetrics(line).practiced,2);
assert.equal(p.dayCount(),2);
assert.equal(p.summary([line,black]).duePositions,0);
time+=86400000+1000;
assert.equal(p.dueLines([line]).length,1,"old positions should be due");
const next=p.noteMove(line,2);
assert.equal(next.level,2);
assert.equal(p.lineMetrics(line).due,1,"missed position remains due");
time+=86400000+1000;
assert.equal(p.lineMetrics(line).due,1,"level 2 interval should be 3 days");
assert.equal(p.isFavorite(line),false);
assert.equal(p.toggleFavorite(line),true);
assert.equal(p.toggleFavorite(line),false);
assert.equal(p.toggleFavorite(line),true);
assert.equal(p.isFavorite(line),true);
p.setGoal(5);
for(let i=0;i<5;i++)p.noteMove(line,4);
assert.equal(p.dayStreak(),1);
const again=createPractice(memory,()=>time);
assert.equal(again.isFavorite(line),true);
assert.equal(again.goal(),5);
assert.equal(again.dayCount(),5); // Five correct moves were made on the last simulated day.
assert.equal(again.dayStreak(),1);
assert.ok(raw.includes("schachnova")===false,"store does not unnecessarily duplicate key names");
raw="{bad json";
assert.equal(createPractice(memory,()=>time).summary([line]).today,0,"corrupt data must recover");
const noStorage=createPractice({getItem(){throw Error("denied");},setItem(){throw Error("full");}},()=>time);
assert.doesNotThrow(()=>noStorage.noteMove(line,0),"offline lessons must survive blocked storage");
assert.ok(/2026-11-03/.test(localDay(new Date(2026,10,3,12).getTime())));
console.log("PASS adaptive practice data persistence, due schedule, hints, favorites, streak, and UI hooks");
